"""Per-model facts sheet for report section 3.2 (raw material, not report text).

    python -m src.eval.model_facts      -> report/model_facts.md

Every number is read from results/model_comparison.csv and results/cv_fold_scores.csv;
the hyperparameter and objective descriptions match src/models/train_models.py and
src/models/tune_hgb.py. Write the report answers in your own words.
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

RES = Path("results")

# (important hyperparameters with initial values, loss / optimisation objective)
SPEC = {
    "baseline_nearest": ("No hyperparameters: score 1 for the nearest candidate (dist_rank == 0), 0 otherwise.",
                         "None (not learned)."),
    "gnb": ("var_smoothing = 1e-9 (sklearn default). No scaling (per-feature Gaussians are scale-invariant).",
            "Maximum-likelihood estimates of a Gaussian mean and variance per feature and class; no iterative loss."),
    "logreg": ("C = 1.0 (inverse L2 strength), solver = lbfgs, max_iter = 2000; StandardScaler fitted inside each fold.",
               "L2-regularised binary log loss (cross-entropy), minimised with L-BFGS."),
    "knn": ("n_neighbors = 25, weights = distance, Euclidean metric; StandardScaler inside each fold; trained on every 10th point (stride 10).",
            "None at training time (stores the training rows); prediction = distance-weighted vote of the 25 nearest rows."),
    "decision_tree": ("max_depth = None (unlimited), min_samples_leaf = 1, criterion = gini.",
                      "Greedy splits that minimise Gini impurity."),
    "random_forest": ("n_estimators = 300, min_samples_leaf = 5, max_features = sqrt, bootstrap = True.",
                      "Each tree: greedy Gini-impurity splits on a bootstrap sample; probabilities = mean of tree votes."),
    "extra_trees": ("n_estimators = 300, min_samples_leaf = 5, max_features = sqrt, bootstrap = False, random split thresholds.",
                    "Gini impurity over randomly drawn thresholds; probabilities = mean of tree votes."),
    "hist_gb": ("learning_rate = 0.1, max_iter = 300, max_leaf_nodes = 31, min_samples_leaf = 20, l2_regularization = 0, "
                "early stopping (10% validation, 10 rounds patience).",
                "Binary log loss (cross-entropy), minimised by gradient boosting of histogram-binned trees."),
    "hist_gb_tuned": ("See results/tuning_comparison.csv and results/optuna_trials.csv for the tuned values; max_iter = 1000 "
                      "with early stopping.",
                      "Training: binary log loss. Search objective: mean CV Top-1 accuracy (Optuna TPE)."),
    "mlp": ("hidden layers (64, 32), ReLU, adam, learning_rate_init = 0.001, alpha (L2) = 1e-4, batch size 200, "
            "max 200 epochs, early stopping on validation accuracy (10% held out, patience 10); StandardScaler inside each fold.",
            "Binary log loss (cross-entropy) with L2 penalty, minimised by Adam."),
}


def main():
    cmp = pd.read_csv(RES / "model_comparison.csv").set_index("model")
    folds = pd.read_csv(RES / "cv_fold_scores.csv")
    order = cmp.sort_values("st_top1_acc", ascending=False).index
    lines = ["# Model facts (raw material for report section 3.2)", "",
             "Generated by `python -m src.eval.model_facts` from `results/`. Numbers only: write the report "
             "answers in your own words.", "",
             "CV = 5 trip-grouped folds on the 80 training trips (validation scored on all usable points). "
             "ST = the 10 student-test trips. Top-1 = share of GPS points whose highest-scoring candidate is the "
             "reference arc. Macro F1 / precision / recall / log loss are on candidate rows at threshold 0.5.", ""]
    lines += ["## Consolidated comparison (report section 3.1)", "",
              "| Model | Family | CV macro F1 | ST Top-1 | ST route continuity | ST macro F1 | ST log loss | Inference (ms / 1k points) |",
              "|---|---|---|---|---|---|---|---|"]
    for m in order:
        r = cmp.loc[m]
        ll = "N/A (hard 0/1 scores)" if pd.isna(r.st_log_loss) else f"{r.st_log_loss:.4f}"
        lines.append(f"| {m} | {r.family} | {r.cv_macro_f1_mean:.4f} ± {r.cv_macro_f1_std:.4f} | {r.st_top1_acc:.4f} | "
                     f"{r.st_route_continuity:.4f} | {r.st_macro_f1:.4f} | {ll} | {r.inference_ms_per_1k_obs:.1f} |")
    lines += ["", "Key configuration per model: see each model's section below.", ""]
    for m in order:
        r = cmp.loc[m]
        f = folds[folds.model == m]
        gap = r.train_macro_f1_mean - r.cv_macro_f1_mean
        hp, loss = SPEC.get(m, ("(not documented)", "(not documented)"))
        ll = "N/A (hard 0/1 scores)" if pd.isna(r.st_log_loss) else f"{r.st_log_loss:.4f}"
        lines += [
            f"## {m}", "",
            f"- **Family:** {r.family}",
            f"- **Configuration:** {r.config}",
            f"- **Important hyperparameters (initial values):** {hp}",
            f"- **Loss / objective:** {loss}",
            f"- **Training rows:** {int(r.train_rows):,} (every {int(r.stride)}th GPS point of each trip, all its candidates)",
            "",
            "| Metric | Value |", "|---|---|",
            f"| CV macro F1 (mean ± std) | {r.cv_macro_f1_mean:.4f} ± {r.cv_macro_f1_std:.4f} |",
            f"| CV macro F1 per fold | {', '.join(f'{v:.4f}' for v in f.sort_values('fold').val_macro_f1)} |",
            f"| CV Top-1 (mean ± std) | {r.cv_top1_mean:.4f} ± {r.cv_top1_std:.4f} |",
            f"| Training-fold macro F1 (mean) | {r.train_macro_f1_mean:.4f} |",
            f"| Train minus CV macro F1 | {gap:+.4f} |",
            f"| ST Top-1 accuracy | {r.st_top1_acc:.4f} |",
            f"| ST macro F1 | {r.st_macro_f1:.4f} |",
            f"| ST precision / recall (match class) | {r.st_precision_pos:.4f} / {r.st_recall_pos:.4f} |",
            f"| ST log loss | {ll} |",
            f"| ST route continuity (classifier only) | {r.st_route_continuity:.4f} |",
            f"| ST candidate miss rate | {r.st_candidate_miss_rate:.4f} |",
            f"| Fit time (final fit) | {r.fit_time_s:.1f} s |",
            f"| Inference per 1,000 GPS points | {r.inference_ms_per_1k_obs:.1f} ms |",
            "",
            "Over/underfitting evidence to discuss: the train-minus-CV gap above, the spread across folds, and "
            "(MLP, HistGB) the training-history plot in `results/figures/`.", ""]
    Path("report").mkdir(exist_ok=True)
    Path("report/model_facts.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote report/model_facts.md for", len(order), "models")


if __name__ == "__main__":
    main()
